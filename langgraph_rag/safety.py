"""
위기 신호 감지와 고정 응답.

이 모듈은 LLM을 부르지 않는다. 그게 요점이다.
자해·자살 암시가 들어온 순간의 출력은 생성 결과에 좌우되면 안 된다 -
프롬프트로 아무리 잘 지시해도 그 한 번의 대화에서 다르게 나올 여지가 남는다.

감지되면 검색도 생성도 건너뛰고 CRISIS_RESPONSE를 그대로 흘려보낸다.

놓치는 쪽(감지 실패)은 회귀 테스트로 덮는다. tests/test_safety.py 참고.

detect_crisis() -> 발화에 위기 신호가 있는지 판정하는 함수
CRISIS_RESPONSE -> 감지 시 그대로 내보내는 고정 문구
"""

import re


# 국내 24시간 상담 창구. 번호를 코드에 박는 이유는, 이 문장만은 검색 결과나 생성에
# 좌우되면 안 되기 때문이다. 번호가 바뀌면 이 상수를 고친다.
CRISIS_RESPONSE = (
    "지금 많이 힘드신 것 같아요. 그 마음을 혼자 견디지 않으셨으면 합니다.\n\n"
    "지금 바로 이야기 나눌 수 있는 곳이 있습니다.\n"
    "자살예방 상담전화 109 (24시간)\n"
    "정신건강 위기상담전화 1577-0199 (24시간)\n"
    "생명의전화 1588-9191 (24시간)\n\n"
    "전화가 어렵다면 가까운 사람에게 지금 곁에 있어 달라고 말해 주세요. "
    "저는 여기 있겠습니다. 준비되시면 다시 이야기해요."
)


# 자해·자살 암시 패턴. 공백을 지운 문자열에 대고 검사한다("죽 고 싶" 같은 변형).
# 반려동물을 잃은 맥락이라 '따라가다', '옆으로 가다' 류의 완곡 표현을 포함한다.
_CRISIS_PATTERNS = [
    r"죽고싶",
    r"죽어버리",
    r"자살",
    r"자해",
    r"목숨을끊",
    r"생을마감",
    r"사라지고싶",
    r"없어지고싶",
    r"끝내고싶",
    r"살고싶지않",
    r"살아갈이유가없",
    r"살아야할이유가없",
    r"의미가없어졌",
    r"따라가고싶",
    r"따라가려",
    r"곁으로가고싶",
    r"옆으로가고싶",
    r"같이가고싶",
    r"나도데려가",
    r"유서",
    r"수면제를모으",
    r"약을모으",
]

_CRISIS_RE = re.compile("|".join(_CRISIS_PATTERNS))


# sabu: 오탐 — "나도 따라가고 싶다"는 유족이 흔히 쓰는 관용 표현이기도 하다.
#       규칙을 넓히면 평범한 그리움 표현마다 상담이 끊기고, 좁히면 진짜 신호를 놓친다.
#       놓치는 쪽은 손대지 마라(회귀 테스트가 지킨다). 오탐만 줄일 때,
#       이 함수는 판정을 참/거짓 하나로 돌려주는 것으로 충분한가?
#       아니라면 무엇이 더 필요하고, 그 값을 받는 쪽은 어떻게 달라져야 하나?
def detect_crisis(text: str) -> bool:
    """
    발화에 자해·자살 암시가 있으면 True.

    공백을 모두 지운 뒤 검사한다. 띄어쓰기를 바꾼 변형까지 같은 규칙으로 잡기 위해서다.
    문맥은 보지 않는다 - 문맥 판단은 LLM의 일이고, 이 경로는 LLM을 쓰지 않기로 한 곳이다.
    """
    return bool(_CRISIS_RE.search(re.sub(r"\s+", "", text or "")))
